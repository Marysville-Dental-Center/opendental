using System.Collections.Generic;
using System.IO;
using System.Text;
using Newtonsoft.Json;

namespace SyntheticData.Validation {
	///<summary>Everything "validate" records about a database. Two reports of the same data are identical, byte for byte: nothing in
	///them depends on when or where the report was made, except the server version.</summary>
	public class ValidationReport {
		public int FormatVersion=1;
		public string Database;
		public string ServerVersion;
		public string AsOf;
		///<summary>The SyntheticDataInfo preference (seed, size, as-of), when the database was generated by this tool.</summary>
		public string GenerationInfo;
		public int TableCount;
		public int ColumnCount;
		public long TotalRows;
		public List<TableReport> Tables=new List<TableReport>();
		///<summary>Business totals and consistency checks by name, from sql/business-totals.sql.</summary>
		public SortedDictionary<string,string> Totals=new SortedDictionary<string,string>();

		public void Save(string path) {
			File.WriteAllText(path,JsonConvert.SerializeObject(this,Formatting.Indented),new UTF8Encoding(false));
		}

		public static ValidationReport Load(string path) {
			return JsonConvert.DeserializeObject<ValidationReport>(File.ReadAllText(path,Encoding.UTF8));
		}

		public string ToJson() {
			return JsonConvert.SerializeObject(this,Formatting.Indented);
		}
	}

	public class TableReport {
		public string Name;
		public long Rows;
		///<summary>CHECKSUM TABLE ... EXTENDED. Depends on the physical row format, so a schema change alters it even when no value changed.</summary>
		public string ChecksumTable;
		///<summary>Per-column checksum: the sum of CRC32(primary key | value) over all rows. Unchanged values give an unchanged checksum
		///whatever happens to other columns.</summary>
		public SortedDictionary<string,string> Columns=new SortedDictionary<string,string>();
	}
}
