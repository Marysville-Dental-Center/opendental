		[TestMethod]
		public void NewValues_ArePinnedToThePublishedNumbers() {
			Assert.AreEqual(8,OdValues.EfPatientList);//25.1
			Assert.AreEqual(9,OdValues.EfInsPick);//25.2
			Assert.AreEqual(28,OdValues.SheetCheck);//25.3
			Assert.AreEqual(4,OdValues.StmtApi);//25.3
			Assert.AreEqual(2,OdValues.AnnotBetterDiagnostics);//24.4
			Assert.AreEqual(6,OdValues.GuardianFather);//25.1 renumbering
			Assert.AreEqual(23,OdValues.GuardianSitter);//25.1 renumbering
			Assert.AreEqual(264,OdValues.PermImageSignatureCreate);
			Assert.AreEqual(265,OdValues.PermSignedImageEdit);
			Assert.AreEqual(266,OdValues.PermBlockoutsFlagged);
			Assert.AreEqual(267,OdValues.PermPayPlanUnlock);
			Assert.AreEqual(270,OdValues.PermProcTPEditFee);
			Assert.AreEqual(271,OdValues.PermEFormImport);
			//The last 24.3 permission is 263, so 264 and up are free in the 24.3 enum.
			Assert.IsTrue((int)EnumPermType.ImageCreate<264);
